"""Compare dist/catalogue.json with NokoPrint's model list (tools/coverage/target-models.tsv).
Usage: python -I tools/pack/check_coverage.py [--write docs/COVERAGE.md]"""
import argparse, csv, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
cat = json.loads((ROOT / "dist" / "catalogue.json").read_text(encoding="utf-8"))
norm = lambda s: re.sub(r"[^a-z0-9]", "", (s or "").lower())

index = {}  # engine -> set of keys
for p in cat["printers"]:
    fname = Path(p["file"]).name.removesuffix(".gz")
    keys = index.setdefault(p["engine"], set())
    keys.add(norm(fname)); keys.add(norm(p["model"])); keys.add(norm(p["manufacturer"] or "") + norm(p["model"]))
    if p["engine"] == "gutenprint":  # stp-<driver>.5.3.sim.ppd
        keys.add(norm(re.sub(r"^stp-|\.\d+\.\d+\.sim\.ppd$", "", fname)))

allkeys = set().union(*index.values())

def keys_for(engine, model, extra):
    ks = {norm(model)}
    if ";*" in model:  # one PPD for several models: "Samsung ML-1670;*ML-1671" -> any listed name counts
        first, *rest = model.split(";*")
        brand = first.split()[0]
        ks |= {norm(first)} | {norm(f"{brand} {r}") for r in rest}
    if engine == "gutenprint" and extra.startswith("DeviceModel="):
        ks.add(norm(extra.split("=", 1)[1]))
    elif extra.endswith(".ppd"):
        ks.add(norm(extra))
    return ks

rows = list(csv.DictReader(open(ROOT / "tools/coverage/target-models.tsv", encoding="utf-8"), delimiter="\t"))
res, missing = {}, {}
for r in rows:
    e = r["engine"]
    ks = keys_for(e, r["model"], r["ppd_or_devicemodel"])
    hit = bool(ks & index.get(e, set())) or (r["model"].startswith("Generic") and bool(ks & allkeys))
    d = res.setdefault(e, [0, 0]); d[1] += 1; d[0] += hit
    if not hit:
        missing.setdefault(e, []).append(r["model"])

lines = ["# Coverage vs NokoPrint 5.28.4", "",
         "Generated by `tools/pack/check_coverage.py`. A target model counts as covered when our catalogue has a PPD whose",
         "file name, model name or Gutenprint driver name matches it.", "",
         "| Engine | Target models | Covered | Missing |", "|---|---|---|---|"]
tot = [0, 0]
for e in ("splix", "escpr", "hplip", "gutenprint"):
    c, t = res.get(e, [0, 0]); tot[0] += c; tot[1] += t
    lines.append(f"| {e} | {t} | {c} | {t - c} |")
lines.append(f"| **all** | {tot[1]} | {tot[0]} | {tot[1] - tot[0]} |")
for e, ms in missing.items():
    lines += ["", f"## Missing from {e} ({len(ms)})", ""] + [f"- {m}" for m in ms[:200]]
    if len(ms) > 200: lines.append(f"- ... {len(ms) - 200} more")
text = "\n".join(lines) + "\n"
ap = argparse.ArgumentParser(); ap.add_argument("--write"); a = ap.parse_args()
if a.write: Path(a.write).write_text(text, encoding="utf-8")
print("\n".join(lines[5:12]))
